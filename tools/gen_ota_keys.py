"""Create the ECDSA P-256 key pair used to sign firmware updates.

    python tools/gen_ota_keys.py

Writes keys/ota_private.pem (git-ignored, keep it secret) and
firmware/include/ota_pubkey.h (public key compiled into the firmware).
"""
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric import ec

ROOT = Path(__file__).resolve().parent.parent
priv_path = ROOT / "keys" / "ota_private.pem"
header_path = ROOT / "firmware" / "include" / "ota_pubkey.h"

if priv_path.exists():
    raise SystemExit(f"{priv_path} already exists; delete it first if you really want a new key")

key = ec.generate_private_key(ec.SECP256R1())
priv_path.parent.mkdir(exist_ok=True)
priv_path.write_bytes(key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                                        serialization.NoEncryption()))
priv_path.chmod(0o600)

pub = key.public_key().public_bytes(serialization.Encoding.PEM, serialization.PublicFormat.SubjectPublicKeyInfo)
lines = "".join(f'    "{line}\\n"\n' for line in pub.decode().strip().splitlines())
header_path.write_text(
    "#pragma once\n"
    "// Public key used to verify signed firmware updates (generated by tools/gen_ota_keys.py).\n"
    "static const char OTA_PUBLIC_KEY_PEM[] =\n" + lines.rstrip("\n") + ";\n"
)
print(f"private key: {priv_path}\npublic key header: {header_path}\nRebuild and flash the firmware over USB once.")
